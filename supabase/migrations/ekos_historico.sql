do $$
declare
  v_familia uuid;
  v_user uuid;
  m record;
  h record;
  v_despesa uuid;
  v_venc date;
  v_inseridos int := 0;
  v_pulados int := 0;
begin
  select familia_id, user_id into v_familia, v_user from public.fin_membros where papel = 'titular' limit 1;

  for m in select * from mapa loop
    v_despesa := null;
    if m.descricao is not null then
      -- A conta da coluna: a atual (de ekos_contas.sql) ou uma inativa, criada só para o histórico
      select id into v_despesa from public.fin_despesas
      where familia_id = v_familia and cartao_id is null and descricao = m.descricao
      order by ativo desc, created_at desc limit 1;
      if v_despesa is null then
        insert into public.fin_despesas (familia_id, user_id, descricao, categoria, valor, frequencia, dia_vencimento, essencial, ativo)
        values (v_familia, v_user, m.descricao, m.categoria, 0, 'mensal', m.dia, true, false)
        returning id into v_despesa;
      end if;
    end if;

    for h in select * from historico where coluna = m.coluna loop
      v_venc := make_date(extract(year from h.mes)::int, extract(month from h.mes)::int,
                          least(m.dia, extract(day from (h.mes + interval '1 month' - interval '1 day'))::int));

      -- Já tem registro dessa conta no mês (ou fatura desse cartão)? Pula
      if exists (
        select 1 from public.fin_lancamentos l
        where l.familia_id = v_familia and l.competencia = h.mes
          and (
            (v_despesa is not null and l.despesa_id = v_despesa)
            or (v_despesa is null and l.despesa_id is null and l.descricao = 'Outros' and l.origem = 'manual' and l.cartao_id is null)
            or (m.cartoes is not null and l.cartao_id in (
                  select c.id from public.fin_cartoes c where c.familia_id = v_familia and c.nome ilike any (m.cartoes)))
          )
      ) then
        v_pulados := v_pulados + 1;
        continue;
      end if;

      insert into public.fin_lancamentos
        (familia_id, user_id, data, vencimento, competencia, descricao, valor, categoria, cartao_id, origem, despesa_id, pago)
      values
        (v_familia, v_user, v_venc, v_venc, h.mes, coalesce(m.descricao, 'Outros'), h.valor, m.categoria, null,
         case when v_despesa is null then 'manual' else 'fixo' end, v_despesa, true);
      v_inseridos := v_inseridos + 1;
    end loop;
  end loop;

  raise notice 'Histórico: % valores importados, % pulados (já existiam)', v_inseridos, v_pulados;
end $$;

